#!/usr/bin/env python3
"""The provisioner's load file, written from the CAP, or checked against it.

    python3 tools/cardkit/make-assets.py [--cap PATH] [--check]

A load file is what gp sends after INSTALL [for load]: C4, its BER length, then
the CAP's components concatenated in the order ant-javacard's
CAPFile._getCode and GlobalPlatformPro's CAPFile.getCode both use -- Header,
Directory, Import, Applet, Class, Method, StaticField, Export, ConstantPool,
RefLocation -- and never the Descriptor (the card reconstructs it) or Debug.
A CAP is a ZIP whose component files all sit under `<package path>/javacard/`;
we read them from there rather than parsing the Header, so this script cannot
disagree with the converter about offsets.

The CAP comes from `ant cap` (docs/CAP-BUILD.md). This script does NOT pin the
CAP's own sha256: the converter stamps the CAP's manifest with the build time,
so that hash moves on every build and a pin on it would fail a correct rebuild.
What must not move is the load file: LOAD_FILE_SIZE and LOAD_FILE_SHA256 below
are the pins, and `--check` fails when a rebuild changes either. The provisioner
checks the same sha256 again before it sends a byte, so a stale asset is caught
twice.

    python3 tools/cardkit/make-assets.py            # write the asset
    python3 tools/cardkit/make-assets.py --check    # write nothing; fail on any difference
"""
import argparse
import hashlib
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

CAP = 'applet/target/fedimint-card-0.1.cap'
# Relative to HERE, not ROOT: the asset sits in this package, and a path relative
# to ROOT writes it to <repo>/gp/ where no test looks.
ASSET = os.path.join(HERE, 'gp/load-file.ts')

# The pins. None means "not pinned yet": the first run fills them in from the
# CAP and refuses --check. They are never a guess -- run the script on a real
# CAP and copy what it prints.
LOAD_FILE_SIZE = 5513
LOAD_FILE_SHA256 = '4411d43e446f1a0a13906465af95eda346e38ed924b23a55565d489f7aa79962'

# ant-javacard's CAPFile.componentNames, in the order getCode writes them.
# Descriptor and Debug are skipped, as getCode(false) skips them.
COMPONENTS = (
    'Header',
    'Directory',
    'Import',
    'Applet',
    'Class',
    'Method',
    'StaticField',
    'Export',
    'ConstantPool',
    'RefLocation',
)


def component_map(zip_file):
    """{component name: bytes} for every javacard/ component file in the CAP."""
    out = {}
    for name in zip_file.namelist():
        if not name.endswith('.cap') or '/javacard/' not in name:
            continue
        base = name.rsplit('/', 1)[-1][:-len('.cap')]
        if base in COMPONENTS or base in ('Descriptor', 'Debug'):
            out[base] = zip_file.read(name)
    return out


def ber(n):
    if n < 0x80:
        return bytes([n])
    if n < 0x100:
        return bytes([0x81, n])
    if n < 0x10000:
        return bytes([0x82, n >> 8, n & 0xFF])
    raise SystemExit('make-assets: %d bytes of components does not fit a load file' % n)


def load_file(path):
    with zipfile.ZipFile(path) as z:
        parts = component_map(z)
    missing = [c for c in ('Header', 'Applet') if c not in parts]
    if missing:
        raise SystemExit(
            'make-assets: %s has no %s component: is it a CAP made by `ant cap`?'
            % (path, ', '.join(missing))
        )
    body = b''.join(parts[c] for c in COMPONENTS if c in parts)
    return b'\xC4' + ber(len(body)) + body


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def header():
    return (
        '// Generated by tools/cardkit/make-assets.py from %s\n'
        '// Do not edit: run the script; CI runs it with --check.\n'
        '//\n'
        '// The load file gp sends after INSTALL [for load]: C4, its length, then the\n'
        '// CAP components in load order, without the Descriptor or Debug.\n'
        '\n' % CAP
    )


def render(data):
    return ''.join([
        header(),
        'export const FEDIMINT_LOAD_FILE = {\n',
        "  name: 'fedimint-card 0.1',\n",
        '  size: %d,\n' % len(data),
        "  sha256: '%s',\n" % sha256(data),
        "  hex: '%s',\n" % data.hex().upper(),
        '};\n',
    ])


def main(argv):
    global LOAD_FILE_SIZE, LOAD_FILE_SHA256
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--cap', default=os.path.join(ROOT, CAP), help='the card CAP (default: %s)' % CAP)
    parser.add_argument('--check', action='store_true', help='write nothing; fail if the asset differs')
    args = parser.parse_args(argv[1:])

    if not os.path.exists(args.cap):
        print(
            'make-assets: no %s\n'
            '  build it:  cd applet && ant cap -Djc.sdk=$HOME/.javacard/sdks/jc305u4_kit\n'
            '  (docs/CAP-BUILD.md)' % os.path.relpath(args.cap, ROOT),
            file=sys.stderr,
        )
        return 1

    data = load_file(args.cap)
    size, digest = len(data), sha256(data)

    if LOAD_FILE_SHA256 is None:
        if args.check:
            print(
                'make-assets: LOAD_FILE_SHA256 is not pinned yet and --check was asked for.\n'
                '  This CAP gives %d bytes, sha256 %s.\n'
                '  Run without --check to write the asset, then pin these two in make-assets.py.'
                % (size, digest),
                file=sys.stderr,
            )
            return 1
        LOAD_FILE_SIZE, LOAD_FILE_SHA256 = size, digest
        print('make-assets: pinning LOAD_FILE_SIZE = %d, LOAD_FILE_SHA256 = %r' % (size, digest))
    elif size != LOAD_FILE_SIZE or digest != LOAD_FILE_SHA256:
        print(
            'make-assets: this CAP gives a load file of %d bytes, sha256 %s;\n'
            '  the pins in make-assets.py say %d, %s.\n'
            '  If the CAP change is wanted, move the pins and the asset together, and say why in the commit.'
            % (size, digest, LOAD_FILE_SIZE, LOAD_FILE_SHA256),
            file=sys.stderr,
        )
        return 1

    text = render(data)
    path = ASSET
    if args.check:
        try:
            with open(path, encoding='utf-8') as f:
                same = f.read() == text
        except FileNotFoundError:
            same = False
        print('%s %s' % ('ok  ' if same else 'DIFF', os.path.relpath(path, ROOT)))
        if not same:
            print(
                'make-assets: the asset is not what the CAP gives: run  python3 tools/cardkit/make-assets.py',
                file=sys.stderr,
            )
            return 1
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote %s' % os.path.relpath(path, ROOT))
    print(
        'load file %d bytes, %d LOAD commands at 247 bytes, sha256 %s'
        % (size, -(-size // 247), digest)
    )
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
